  CONFIG.passcodeHash = CONFIG.passcodeHash || "";
  CONFIG.idleLockMinutes = CONFIG.idleLockMinutes || 10;

  function ghlUrl(path) {
    return CONFIG.ghlBase + "/v2/location/" + CONFIG.locationId + path;
  }

  // ---------------------------------------------------------------------
  // GHL API client
  // ---------------------------------------------------------------------
  function ghlApi(path, opts) {
    opts = opts || {};
    var headers = {
      Authorization: "Bearer " + CONFIG.privateToken,
      Version: opts.version || CONFIG.apiVersions.objects,
    };
    if (opts.body) headers["Content-Type"] = "application/json";
    return fetch(CONFIG.apiBase + path, {
      method: opts.method || "GET",
      headers: headers,
      body: opts.body ? JSON.stringify(opts.body) : undefined,
    }).then(function (res) {
      if (!res.ok) {
        return res
          .text()
          .then(function (t) {
            throw new Error("GHL API " + res.status + " " + path + ": " + t.slice(0, 300));
          });
      }
      return res.json();
    });
  }

  function qs(params) {
    return Object.keys(params)
      .filter(function (k) { return params[k] !== undefined && params[k] !== null && params[k] !== ""; })
      .map(function (k) { return encodeURIComponent(k) + "=" + encodeURIComponent(params[k]); })
      .join("&");
  }

  function loadPipelines() {
    return ghlApi("/opportunities/pipelines?" + qs({ locationId: CONFIG.locationId }), { version: CONFIG.apiVersions.pipelines }).then(function (res) {
      return res.pipelines || [];
    });
  }

  // Paginates /opportunities/search for a single pipeline. Stops when a page
  // comes back shorter than the page size, or after a hard safety cap.
  function loadAllOpportunities(pipelineId) {
    var limit = 100;
    var page = 1;
    var all = [];
    function next() {
      var url =
        "/opportunities/search?" +
        qs({ location_id: CONFIG.locationId, pipeline_id: pipelineId, status: "all", limit: limit, page: page });
      return ghlApi(url, { version: CONFIG.apiVersions.opportunities }).then(function (res) {
        var batch = res.opportunities || [];
        all = all.concat(batch);
        if (batch.length < limit || page > 20) return all;
        page += 1;
        return next();
      });
    }
    return next();
  }

  // GHL's REST API needs a custom object's schemaKey fully qualified as
  // "custom_objects.<key>" in the URL path (confirmed 2026-09-17 against a
  // real location's GET /objects/ listing — a bare key like "trucks" is
  // rejected with 400 "Invalid Key Passed"). CONFIG.objectKeys stays as the
  // short/bare form because ghlUrl()'s "open in GHL" deep-links use that
  // same short form in their own, unrelated URL scheme (/v2/location/:id/
  // objects/:key/list) — only the REST API calls need this prefix, so it's
  // applied here at the point of use rather than baked into CONFIG.objectKeys.
  function objectSchemaKey(shortKey) {
    return "custom_objects." + shortKey;
  }

  // Paginates POST /objects/:schemaKey/records/search using searchAfter.
  function loadAllObjectRecords(schemaKey) {
    var pageLimit = 100;
    var all = [];
    function next(searchAfter) {
      var body = { locationId: CONFIG.locationId, page: 1, pageLimit: pageLimit, query: "" };
      if (searchAfter) body.searchAfter = searchAfter;
      return ghlApi("/objects/" + objectSchemaKey(schemaKey) + "/records/search", { method: "POST", version: CONFIG.apiVersions.objects, body: body }).then(function (res) {
        var batch = res.records || [];
        all = all.concat(batch);
        if (batch.length < pageLimit || all.length > 5000) return all;
        var last = batch[batch.length - 1];
        return next(last && last.searchAfter);
      });
    }
    return next(null);
  }

  function propVal(v) {
    // Currency-shaped properties come back as {currency, value}; everything
    // else is a plain scalar.
    if (v && typeof v === "object" && "value" in v) return v.value;
    return v;
  }

  // ---------------------------------------------------------------------
  // Property mappers: GHL record -> the row shape the existing UI expects
  // ---------------------------------------------------------------------
  function mapDriver(rec) {
    var p = rec.properties || {};
    return {
      recordId: rec.id,
      name: p.driver_name,
      driverId: p.driver_id,
      status: p.employment_status,
      type: p.employment_type,
      hireDate: p.hire_date,
      email: p.email,
    };
  }

  function mapTruck(rec) {
    var p = rec.properties || {};
    return {
      recordId: rec.id,
      unit: p.unit_number,
      yr: p.year,
      make: p.make,
      model: p.model,
      status: p.status,
      mileage: p.current_mileage,
      driver: p.primary_driver,
      nextService: p.next_service_date,
      regExp: p.registration_expiration,
      insExp: p.insurance_expiration,
    };
  }

  function mapMaintenance(rec) {
    var p = rec.properties || {};
    return {
      recordId: rec.id,
      id: p.maintenance_id,
      truck: p.truck_unit,
      type: p.maintenance_type,
      serviceDate: p.service_date,
      cost: propVal(p.cost),
      status: p.status,
      nextService: p.next_service_date,
      provider: p.service_provider,
    };
  }

  function mapTraining(rec) {
    var p = rec.properties || {};
    return {
      recordId: rec.id,
      id: p.training_id,
      driver: p.driver_name,
      title: p.training_title,
      type: p.training_type,
      date: p.training_date,
      status: p.status,
    };
  }

  function mapQuarter(rec) {
    var p = rec.properties || {};
    return {
      recordId: rec.id,
      driver: p.driver_name,
      quarter: p.quarter,
      year: p.year,
      completedJobs: p.completed_tow_jobs,
      totalJobs: p.total_tow_jobs,
      rating: p.performance_rating,
      status: p.status,
      revenue: propVal(p.total_revenue),
      commission: propVal(p.commission_earned),
      netCommission: propVal(p.net_commission),
    };
  }

  function mapAaa(rec) {
    var p = rec.properties || {};
    var gross = propVal(p.gross_paid_amount);
    var expected = propVal(p.expected_tow_amount);
    var diff = p.payment_difference_value;
    if (diff === undefined && gross != null && expected != null) diff = gross - expected;
    return {
      recordId: rec.id,
      id: p.aaa_payment_id,
      wo: p.work_order_number,
      status: p.reconciliation_status,
      gross: gross,
      expected: expected,
      diff: diff,
      reason: p.exception_reason || (diff > 0 ? "Overpaid by AAA" : diff < 0 ? "Underpaid by AAA" : null),
    };
  }

  // ---------------------------------------------------------------------
  // State + loaders
  // ---------------------------------------------------------------------
  var state = {
    meta: null,
    aaaSummary: null,
    aaaSamples: null,
    dispatch: null,
    drivers: null,
    fleet: null,
    maintenance: null,
    training: null,
    quarters: null,
  };

  var stageNameById = {};

  function loadDispatch() {
    return loadPipelines().then(function (pipelines) {
      var pipeline = pipelines.filter(function (p) {
        return (p.name || "").toLowerCase() === CONFIG.dispatchPipelineName.toLowerCase();
      })[0];
      if (!pipeline) throw new Error('No pipeline named "' + CONFIG.dispatchPipelineName + '" found in this GHL location.');
      stageNameById = {};
      (pipeline.stages || []).forEach(function (s) { stageNameById[s.id] = s.name; });
      return loadAllOpportunities(pipeline.id).then(function (opps) {
        var stageCounts = {};
        var rows = opps.map(function (o) {
          var stageName = stageNameById[o.pipelineStageId] || o.pipelineStageId;
          stageCounts[stageName] = (stageCounts[stageName] || 0) + 1;
          return {
            name: o.name,
            stage: stageName,
            status: o.status,
            value: o.monetaryValue,
            updatedAt: o.updatedAt,
            contactId: o.contactId,
          };
        });
        state.dispatch = {
          opportunities: rows,
          stageCounts: stageCounts,
          pipelineName: pipeline.name,
          total: rows.length,
        };
      });
    });
  }

  function loadDrivers() {
    return loadAllObjectRecords(CONFIG.objectKeys.drivers).then(function (recs) {
      var rows = recs.map(mapDriver);
      state.drivers = { records: rows, total: rows.length };
    });
  }

  function loadFleet() {
    return loadAllObjectRecords(CONFIG.objectKeys.fleet).then(function (recs) {
      var rows = recs.map(mapTruck);
      state.fleet = { records: rows, total: rows.length };
    });
  }

  function loadMaintenance() {
    return loadAllObjectRecords(CONFIG.objectKeys.maintenance).then(function (recs) {
      state.maintenance = { records: recs.map(mapMaintenance) };
    });
  }

  function loadTraining() {
    return loadAllObjectRecords(CONFIG.objectKeys.training).then(function (recs) {
      state.training = { records: recs.map(mapTraining) };
    });
  }

  function loadQuarters() {
    return loadAllObjectRecords(CONFIG.objectKeys.quarters).then(function (recs) {
      state.quarters = { records: recs.map(mapQuarter) };
    });
  }

  function loadAaa() {
    return loadAllObjectRecords(CONFIG.objectKeys.aaa).then(function (recs) {
      var rows = recs.map(mapAaa);
      var statusCounts = {};
      var missingWo = 0;
      rows.forEach(function (r) {
        var key = (r.status || "unknown").toLowerCase();
        statusCounts[key] = (statusCounts[key] || 0) + 1;
        if (!r.wo) missingWo += 1;
      });
      var exceptions = rows
        .filter(function (r) { return (r.status || "").toLowerCase() === "exception"; })
        .sort(function (a, b) { return Math.abs(Number(b.diff) || 0) - Math.abs(Number(a.diff) || 0); })
        .slice(0, 25);
      var matchedSample = rows.filter(function (r) { return (r.status || "").toLowerCase() === "matched"; }).slice(0, 25);
      state.aaaSummary = { total: rows.length, status_counts: statusCounts, missing_work_order: missingWo };
      state.aaaSamples = { exceptions: exceptions, unmatched: matchedSample };
    });
  }

  function loadMeta() {
    var counts = {
      drivers: (state.drivers && state.drivers.total) || 0,
      fleet: (state.fleet && state.fleet.total) || 0,
    };
    state.meta = { lastSynced: new Date().toISOString(), objectCounts: counts };
  }

  function loadAll() {
    return Promise.all([loadDispatch(), loadDrivers(), loadFleet(), loadMaintenance(), loadTraining(), loadQuarters(), loadAaa()]).then(loadMeta);
  }

