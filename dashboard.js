    function buildTable(columns, rows, linkFn) {
      if (!rows || !rows.length) {
        return '<div class="tableWrap"><div class="empty">No records synced for this yet.</div></div>';
      }
      var head = columns.map(function (c) { return "<th>" + c.label + "</th>"; }).join("");
      var body = rows.map(function (r) {
        var url = linkFn ? linkFn(r) : null;
        var cells = columns.map(function (c, i) {
          var html = c.render(r);
          if (url) {
            var cls = i === 0 ? "rowlink" : "cellLink";
            html = '<a class="' + cls + '" href="' + escAttr(url) + '" target="_blank" rel="noopener">' + html + "</a>";
          }
          return "<td>" + html + "</td>";
        }).join("");
        var trOpen = url ? '<tr class="clickable">' : "<tr>";
        return trOpen + cells + "</tr>";
      }).join("");
      return '<div class="tableWrap"><table><thead><tr>' + head + "</tr></thead><tbody>" + body + "</tbody></table></div>";
    }

