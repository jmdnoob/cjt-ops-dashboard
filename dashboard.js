    function daysUntil(dateStr) {
      if (!dateStr) return null;
      var d = new Date(dateStr);
      if (isNaN(d.getTime())) return null;
      var now = new Date();
      d.setHours(0, 0, 0, 0);
      now.setHours(0, 0, 0, 0);
      return Math.round((d - now) / 86400000);
    }
    function dueBadge(days) {
      if (days === null) return "";
      if (days < 0) return '<span class="due-badge due-overdue">' + Math.abs(days) + "d overdue</span>";
      if (days === 0) return '<span class="due-badge due-today">Due today</span>';
      if (days <= 14) return '<span class="due-badge due-soon">In ' + days + "d</span>";
      return '<span class="due-badge due-later">In ' + days + "d</span>";
    }
    function daysAgoLabel(dateStr) {
      if (!dateStr) return "";
      var d = new Date(dateStr);
      if (isNaN(d.getTime())) return "";
      var days = Math.floor((new Date() - d) / 86400000);
      if (days <= 0) return "Today";
      if (days === 1) return "1 day ago";
      return days + " days ago";
    }
    function diffChip(diff) {
      var n = Number(diff);
      if (isNaN(n) || n === 0) return "";
      var cls = n > 0 ? "amber" : "red";
      var sign = n > 0 ? "+" : "−";
      var amt = "$" + Math.abs(n).toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
      return '<span class="chip ' + cls + '">' + sign + amt + "</span>";
    }
    function prefersReducedMotion() {
      return !!(window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches);
    }
    function animateValueText(el, finalText) {
      var m = String(finalText).match(/^(\$?)([\d,]+(?:\.\d+)?)(.*)$/);
      if (!m || prefersReducedMotion()) {
        el.textContent = finalText;
        return;
      }
      var prefix = m[1], numStr = m[2], suffix = m[3];
      var target = parseFloat(numStr.replace(/,/g, ""));
      if (isNaN(target)) {
        el.textContent = finalText;
        return;
      }
      var decimals = numStr.indexOf(".") !== -1 ? (numStr.split(".")[1] || "").length : 0;
      var duration = 650;
      var start = null;
      function step(ts) {
        if (start === null) start = ts;
        var progress = Math.min((ts - start) / duration, 1);
        var eased = 1 - Math.pow(1 - progress, 3);
        el.textContent = prefix + (target * eased).toLocaleString(undefined, { minimumFractionDigits: decimals, maximumFractionDigits: decimals }) + suffix;
        if (progress < 1) requestAnimationFrame(step);
        else {
          el.textContent = finalText;
          el.classList.add("pulseIn");
          setTimeout(function () { el.classList.remove("pulseIn"); }, 700);
        }
      }
      requestAnimationFrame(step);
    }

